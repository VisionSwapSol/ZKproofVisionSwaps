// Puts the real circuit source behind "Stay unseen." on the landing page.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "circuits", "src", "transaction.circom"), "utf8");
const body = src
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .split(/\r?\n/)
  .filter((l) => !l.startsWith("include") && l.trim() !== "")
  .join("\n");
const out = `// @generated by scripts/sync-excerpt.mjs from circuits/src/transaction.circom\nexport const CIRCUIT_EXCERPT = ${JSON.stringify(body)};\n`;
writeFileSync(join(root, "web", "src", "lib", "excerpt.ts"), out);
console.log("excerpt:", body.split("\n").length, "lines");
