// Writes the verifying key and the empty-tree ladder into the program as Rust constants.
// Run after every trusted-setup change:  node --import tsx sdk/scripts/gen-rust.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { toBE, FIELD } from "../src/field.ts";
import { zeros } from "../src/tree.ts";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const vkPath = join(repo, "circuits", "artifacts", "verification_key.json");
const vkRaw = readFileSync(vkPath);
const vk = JSON.parse(vkRaw.toString("utf8"));

const arr = (b: Uint8Array) => {
  const parts: string[] = [];
  for (let i = 0; i < b.length; i += 16) {
    parts.push("    " + Array.from(b.slice(i, i + 16), (x) => `${x}`).join(", ") + ",");
  }
  return `[\n${parts.join("\n")}\n]`;
};
const g1 = (p: string[]) => {
  const out = new Uint8Array(64);
  out.set(toBE(BigInt(p[0])), 0);
  out.set(toBE(BigInt(p[1])), 32);
  return out;
};
const g2 = (p: string[][]) => {
  const out = new Uint8Array(128);
  out.set(toBE(BigInt(p[0][1])), 0);
  out.set(toBE(BigInt(p[0][0])), 32);
  out.set(toBE(BigInt(p[1][1])), 64);
  out.set(toBE(BigInt(p[1][0])), 96);
  return out;
};

if (vk.protocol !== "groth16" || vk.curve !== "bn128") throw new Error("unexpected verifying key");
if (vk.nPublic !== 7 || vk.IC.length !== 8) throw new Error(`expected 7 public inputs, got ${vk.nPublic}`);

const z = zeros();
const lines: string[] = [];
lines.push("// @generated by sdk/scripts/gen-rust.ts. Do not edit by hand.");
lines.push(`// verification_key.json sha256: ${createHash("sha256").update(vkRaw).digest("hex")}`);
lines.push("");
lines.push("/// BN254 scalar field modulus, big-endian.");
lines.push(`pub const FIELD_MODULUS: [u8; 32] = ${arr(toBE(FIELD))};`);
lines.push("");
lines.push(`pub const VK_ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};`);
lines.push(`pub const VK_BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};`);
lines.push(`pub const VK_GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};`);
lines.push(`pub const VK_DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};`);
lines.push(`pub const VK_IC: [[u8; 64]; 8] = [`);
for (const p of vk.IC) lines.push(`    ${arr(g1(p)).replace(/\n/g, "\n    ")},`);
lines.push("];");
lines.push("");
lines.push("/// zeros[i] = root of an empty subtree of height i; zeros[0] is the empty leaf.");
lines.push(`pub const ZEROS: [[u8; 32]; 27] = [`);
for (const v of z) lines.push(`    ${arr(toBE(v)).replace(/\n/g, "\n    ")},`);
lines.push("];");
lines.push("");

const out = join(repo, "program", "programs", "vision_pool", "src", "constants.rs");
writeFileSync(out, lines.join("\n"));
console.log("wrote", out);
